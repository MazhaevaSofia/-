"""Доска расследований: оценка отдельного дела по счёту финального теста.

Использует ту же шкалу (80% / 50%), что уже была продублирована в отчётах
всех 7 сценариев-расследований (см. game/ui/quiz_engine.py и
_draw_report в каждом из них) — здесь она вынесена в одно место, чтобы
доска расследований показывала оценки, совпадающие с тем, что игрок уже
видел на экране отчёта по конкретному делу.
"""


def grade_for_score(score, max_score):
    """Возвращает (tag, текст) — tag семантический («success»/«warning»/«danger»)."""
    ratio = (score / max_score) if max_score else 0
    if ratio >= 0.8:
        return "success", "ОТЛИЧНО"
    if ratio >= 0.5:
        return "warning", "ХОРОШО"
    if score and score > 0:
        return "warning", "УДОВЛЕТВОРИТЕЛЬНО"
    return "danger", "НЕУДОВЛЕТВОРИТЕЛЬНО"
