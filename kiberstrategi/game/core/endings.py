"""Концовки титров кампании — короткий нарративный итог в зависимости от
процента прохождения. Отдельный модуль (а не хардкод в credits_scene.py),
чтобы тот же текст можно было переиспользовать где-то ещё (например, в
карточке результата), не трогая вёрстку экрана.

tag — семантический цвет («success» / «warning» / «danger»), а не сам
цвет темы: UI-слой сам решает, во что его раскрасить.
"""

# (порог %, tag, заголовок, описание) — проверяются по убыванию порога
ENDINGS = [
    (90, "success", "Утечка предотвращена",
     "Компания в безопасности — вы отразили атаки практически без ошибок."),
    (70, "success", "Угроза нейтрализована",
     "Большинство инцидентов успешно расследовано. Ещё немного практики — и не будет равных."),
    (40, "warning", "Ценой потерь",
     "Часть данных всё же пострадала, но вы усвоили урок и знаете, что исправить."),
    (0, "danger", "Компания пострадала",
     "Слишком много угроз осталось незамеченными. Стоит повторить материал и попробовать снова."),
]


def ending_for_percent(percent):
    """Возвращает (tag, заголовок, описание) для итогового процента прохождения кампании."""
    for threshold, tag, title, description in ENDINGS:
        if percent >= threshold:
            return tag, title, description
    _, tag, title, description = ENDINGS[-1]
    return tag, title, description
